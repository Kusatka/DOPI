import tkinter as tk
from tkinter import messagebox

# Словарь: слово -> (класс, значение)
СЛОВАРЬ = {"ноль": ("ноль", 0)}
for i, w in enumerate("один два три четыре пять шесть семь восемь девять".split(), 1):
    СЛОВАРЬ[w] = ("единицы", i)
for i, w in enumerate("десять одиннадцать двенадцать тринадцать четырнадцать пятнадцать "
                      "шестнадцать семнадцать восемнадцать девятнадцать".split(), 10):
    СЛОВАРЬ[w] = ("надцать", i)
for i, w in enumerate("двадцать тридцать сорок пятьдесят шестьдесят семьдесят "
                      "восемьдесят девяносто".split(), 2):
    СЛОВАРЬ[w] = ("десятки", i * 10)
for i, w in enumerate("сто двести триста четыреста пятьсот шестьсот семьсот "
                      "восемьсот девятьсот".split(), 1):
    СЛОВАРЬ[w] = ("сотни", i * 100)

# Дерево разбора: что может идти после класса
МОЖНО_ПОСЛЕ = {
    "начало":  {"сотни", "десятки", "надцать", "единицы", "ноль"},
    "сотни":   {"десятки", "надцать", "единицы"},
    "десятки": {"единицы"},
    "надцать": set(),
    "единицы": set(),
    "ноль":    set(),
}
ПОСЛЕ = {"сотни": "сотен", "десятки": "десятков", "надцать": "чисел 10–19",
         "единицы": "единиц", "ноль": "нуля"}
КТО = {"сотни": "сотни", "десятки": "десятки", "надцать": "числа 10–19",
       "единицы": "единицы", "ноль": "ноль"}


def перевести(текст):
    слова = текст.lower().split()
    if not слова:
        return None, "Введите число словами"
    пред, пред_слово = "начало", ""
    for номер, слово in enumerate(слова, 1):     # один проход: до первой ошибки
        if слово not in СЛОВАРЬ:                  # лексический анализ
            return None, f"Ошибка в {номер}-м слове ({слово})"
        класс = СЛОВАРЬ[слово][0]
        if класс not in МОЖНО_ПОСЛЕ[пред]:       # синтаксический анализ
            идти = "не может идти" if класс == "ноль" else "не могут идти"
            return None, f"После {ПОСЛЕ[пред]} ({пред_слово}) {идти} {КТО[класс]} ({слово})!"
        пред, пред_слово = класс, слово
    return sum(СЛОВАРЬ[с][1] for с in слова), None   # генерация


def по_кнопке():
    число, ошибка = перевести(вход.get())
    выход.config(text="")
    if ошибка:
        messagebox.showerror("Ошибка ввода", ошибка)
    else:
        выход.config(text=str(число))


if __name__ == "__main__":
    окно = tk.Tk()
    окно.title("Число прописью")
    вход = tk.Entry(окно, width=40)
    вход.pack(padx=10, pady=5)
    вход.bind("<Return>", lambda e: по_кнопке())
    tk.Button(окно, text="Перевести", command=по_кнопке).pack()
    выход = tk.Label(окно, text="", font=("Arial", 16))
    выход.pack(pady=5)
    окно.mainloop()
