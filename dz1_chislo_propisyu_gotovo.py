# ДЗ-1, вариант 4 (русский язык).
# Вход: число от 0 до 999 словами. Выход: число цифрами либо сообщение об ошибке
# во всплывающем окне.
#
# БНФ:
#   Число   = "ноль" ! Сотни </ Хвост /> ! Хвост
#   Хвост   = Десятки </ Единицы /> ! Надцать ! Единицы
#   Сотни   = "сто" ! "двести" ! . . . ! "девятьсот"
#   Десятки = "двадцать" ! "тридцать" ! . . . ! "девяносто"
#   Надцать = "десять" ! "одиннадцать" ! . . . ! "девятнадцать"
#   Единицы = "один" ! "два" ! . . . ! "девять"
#
# Синтаксически управляемый перевод: одно предложение БНФ = одна блок-схема =
# одна функция (число, хвост). Транслятор однопроходный: каждое слово
# проверяется по словарю (лексический анализ, функция слово) прямо в момент,
# когда синтаксический анализ до него дошёл. Поэтому сообщение всегда
# указывает на ПЕРВУЮ по тексту ошибку — диагностика до первой ошибки.

import sys


# ---------------------------------------------------------------
# 1. Словарь языка: слово -> (класс, значение).
# ---------------------------------------------------------------
СОТНИ = ["сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот",
         "семьсот", "восемьсот", "девятьсот"]
ДЕСЯТКИ = ["двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят",
           "семьдесят", "восемьдесят", "девяносто"]
НАДЦАТЬ = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
           "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"]
ЕДИНИЦЫ = ["один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]

СЛОВАРЬ = {"ноль": ("ноль", 0)}
for k, w in enumerate(СОТНИ, 1):
    СЛОВАРЬ[w] = ("сотни", 100 * k)
for k, w in enumerate(ДЕСЯТКИ, 2):
    СЛОВАРЬ[w] = ("десятки", 10 * k)
for k, w in enumerate(НАДЦАТЬ, 10):
    СЛОВАРЬ[w] = ("надцать", k)
for k, w in enumerate(ЕДИНИЦЫ, 1):
    СЛОВАРЬ[w] = ("единицы", k)

# Как класс называть в сообщениях об ошибках.
ПОСЛЕ_КОГО = {"сотни": "сотен", "десятки": "десятков", "надцать": "чисел 10–19",
              "единицы": "единиц", "ноль": "нуля"}
КТО = {"сотни": "сотни", "десятки": "десятки", "надцать": "числа 10–19",
       "единицы": "единицы", "ноль": "ноль"}


class ОшибкаВвода(Exception):
    """Выход по ветке ИНАЧЕ: сообщение и выход."""


# ---------------------------------------------------------------
# 2. Транслятор. Состояние разбора: список слов, K — их число,
#    i — номер текущего слова (с единицы, как на схемах).
# ---------------------------------------------------------------
class Разбор:
    def __init__(self, текст):
        self.слова = текст.lower().replace("ё", "е").split()
        self.исходные = текст.split()          # для сообщений — как ввёл человек
        self.K = len(self.слова)
        self.i = 1
        self.сумма = 0

    # --- Слово i: лексический анализ одного слова (схема «Слово») ---
    def слово(self, i):
        w = self.слова[i - 1]
        if w not in СЛОВАРЬ:
            raise ОшибкаВвода(f"Ошибка в {i}-м слове ({self.исходные[i - 1]}): такого слова нет!")
        return СЛОВАРЬ[w]

    def принять(self, значение):
        self.сумма += значение
        self.i += 1

    def ошибка_порядка(self):
        """После <класс i−1> (слово i−1) не могут идти <класс i> (слово i)!"""
        пред, _ = self.слово(self.i - 1)
        тек, _ = self.слово(self.i)
        глагол = "не может идти" if тек == "ноль" else "не могут идти"
        raise ОшибкаВвода(f"После {ПОСЛЕ_КОГО[пред]} ({self.исходные[self.i - 2]}) "
                          f"{глагол} {КТО[тек]} ({self.исходные[self.i - 1]})!")

    # --- Число = "ноль" ! Сотни </ Хвост /> ! Хвост ---
    def число(self):
        класс, значение = self.слово(self.i)
        if класс == "ноль":
            self.принять(значение)
        elif класс == "сотни":
            self.принять(значение)
            if self.i <= self.K:                # </ Хвост />: есть ещё слова?
                self.хвост()
        else:
            self.хвост()
        if self.i <= self.K:                    # слова остались — лишнее слово
            self.ошибка_порядка()

    # --- Хвост = Десятки </ Единицы /> ! Надцать ! Единицы ---
    def хвост(self):
        класс, значение = self.слово(self.i)
        if класс == "десятки":
            self.принять(значение)
            if self.i <= self.K:                # </ Единицы />
                класс2, значение2 = self.слово(self.i)
                if класс2 == "единицы":
                    self.принять(значение2)
        elif класс in ("надцать", "единицы"):
            self.принять(значение)
        else:                                   # ИНАЧЕ
            self.ошибка_порядка()


def перевести(текст):
    """Возвращает (число, None) или (None, текст ошибки)."""
    р = Разбор(текст)
    if р.K == 0:
        return None, "Введите число словами"
    try:
        р.число()
    except ОшибкаВвода as e:
        return None, str(e)
    return р.сумма, None


