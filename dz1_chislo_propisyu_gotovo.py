# 3. Окно.
# ---------------------------------------------------------------
def запустить_окно():
    import tkinter as tk
    from tkinter import messagebox

    def по_кнопке():
        число, ошибка = перевести(поле_ввода.get())
        поле_результата.config(state="normal")
        поле_результата.delete(0, tk.END)
        if ошибка:
            поле_результата.config(state="readonly")
            messagebox.showerror("Ошибка ввода", ошибка)
        else:
            поле_результата.insert(0, str(число))
            поле_результата.config(state="readonly")

    окно = tk.Tk()
    окно.title("Число прописью → цифрами")
    окно.geometry("520x190")

    tk.Label(окно, text="Число словами (от 0 до 999):").pack(anchor="w", padx=12, pady=(12, 0))
    поле_ввода = tk.Entry(окно, font=("Segoe UI", 12))
    поле_ввода.pack(fill="x", padx=12)
    поле_ввода.focus_set()

    tk.Button(окно, text="Перевести", command=по_кнопке).pack(pady=8)

    tk.Label(окно, text="Число цифрами:").pack(anchor="w", padx=12)
    поле_результата = tk.Entry(окно, font=("Segoe UI", 12), state="readonly")
    поле_результата.pack(fill="x", padx=12)

    поле_ввода.bind("<Return>", lambda событие: по_кнопке())
    окно.mainloop()


