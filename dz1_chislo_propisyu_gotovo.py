    провалы = 0
    for текст, ждём in ТЕСТЫ_ВЕРНЫЕ.items():
        число, ошибка = перевести(текст)
        if число != ждём:
            провалы += 1
            print(f"ПРОВАЛ: «{текст}» -> {число!r}, {ошибка!r}; ждали {ждём}")
    for текст, ждём in ТЕСТЫ_ОШИБОЧНЫЕ.items():
        число, ошибка = перевести(текст)
        if ошибка != ждём:
            провалы += 1
            print(f"ПРОВАЛ: «{текст}» -> {ошибка!r}; ждали {ждём!r}")
    for n in range(1000):
        if перевести(словами(n)) != (n, None):
            провалы += 1
            print(f"ПРОВАЛ: «{словами(n)}» -> {перевести(словами(n))}; ждали {n}")
    print("Все тесты прошли (включая 0–999 полностью)" if провалы == 0 else f"Провалов: {провалы}")
    return провалы


