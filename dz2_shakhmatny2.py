def запустить_окно():
    import tkinter as tk
    from tkinter import messagebox

    def по_кнопке():
        результат, ошибка = выполнить(поле1.get(), поле2.get())
        поле3.config(state="normal")
        поле3.delete(0, tk.END)
        if ошибка:
            поле3.config(state="readonly")
            messagebox.showerror("Ошибка", ошибка)
        else:
            поле3.insert(0, результат)
            поле3.config(state="readonly")

    def очистить():
        поле1.delete(0, tk.END)
        поле2.delete(0, tk.END)
        поле3.config(state="normal")
        поле3.delete(0, tk.END)
        поле3.config(state="readonly")
        поле1.focus_set()

    окно = tk.Tk()
    окно.title("Шахматный порядок чисел")
    окно.geometry("620x260")

    tk.Label(окно, text="Первая строка (числа через пробел):").pack(anchor="w", padx=12, pady=(12, 0))
    поле1 = tk.Entry(окно, font=("Segoe UI", 12))
    поле1.pack(fill="x", padx=12)

    tk.Label(окно, text="Вторая строка (числа через пробел):").pack(anchor="w", padx=12, pady=(8, 0))
    поле2 = tk.Entry(окно, font=("Segoe UI", 12))
    поле2.pack(fill="x", padx=12)

    кнопки = tk.Frame(окно)
    кнопки.pack(pady=10)
    tk.Button(кнопки, text="Вывести в шахматном порядке", command=по_кнопке).pack(side="left", padx=5)
    tk.Button(кнопки, text="Очистить", command=очистить).pack(side="left", padx=5)

    tk.Label(окно, text="Третья строка (результат):").pack(anchor="w", padx=12)
    поле3 = tk.Entry(окно, font=("Segoe UI", 12), state="readonly")
    поле3.pack(fill="x", padx=12)

    for поле in (поле1, поле2):
        поле.bind("<Return>", lambda событие: по_кнопке())
    поле1.focus_set()
    окно.mainloop()


