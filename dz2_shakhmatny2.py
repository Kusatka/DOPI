# В две строки через пробел подаются числа. Необходимо распечатать числа в третьей
# строке в шахматном порядке: первое число первой строки, первое число второй строки,
# второе число первой строки и т.д. Если одна строка длиннее, её остаток
# дописывается в конец. Ошибки ввода — во всплывающем окне (до первой ошибки).

import re
import sys

# Число: целое или вещественное, можно со знаком: 7, -12, 3.5, 0,25
ЧИСЛО = re.compile(r"[+-]?[0-9]+([.,][0-9]+)?")   # только цифры 0–9


class ОшибкаВвода(Exception):
    """Ветка ИНАЧЕ: сообщение и выход."""


def разобрать_строку(текст, номер_строки):
    """Строка -> список чисел (как их ввели). Проверка слева направо до первой ошибки."""
    слова = текст.split()                      # несколько пробелов подряд не мешают
    if not слова:
        raise ОшибкаВвода(f"{номер_строки}-я строка пустая. Введите числа через пробел.")
    for номер, слово in enumerate(слова, start=1):
        if not ЧИСЛО.fullmatch(слово):
            raise ОшибкаВвода(f"Ошибка: '{слово}' не является корректным числом! "
                              f"({номер_строки}-я строка, {номер}-е слово)")
    return слова


def шахматный_порядок(первая, вторая):
    """Чередуем элементы двух списков; остаток более длинного — в конец."""
    результат = []
    i = 0
    while i < len(первая) or i < len(вторая):
        if i < len(первая):
            результат.append(первая[i])
        if i < len(вторая):
            результат.append(вторая[i])
        i += 1
    return результат


def выполнить(текст1, текст2):
    """Возвращает (строка-результат, None) или (None, текст ошибки)."""
    try:
        первая = разобрать_строку(текст1, 1)
        вторая = разобрать_строку(текст2, 2)
    except ОшибкаВвода as e:
        return None, str(e)
    return " ".join(шахматный_порядок(первая, вторая)), None


