def словами(n):
    if n == 0:
        return "ноль"
    с, о = divmod(n, 100)
    части = [СОТНИ[с - 1]] if с else []
    if 10 <= о <= 19:
        части.append(НАДЦАТЬ[о - 10])
    else:
        if о // 10:
            части.append(ДЕСЯТКИ[о // 10 - 2])
        if о % 10:
            части.append(ЕДИНИЦЫ[о % 10 - 1])
    return " ".join(части)


