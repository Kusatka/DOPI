# ДЗ-1, вариант 4 (русский язык).
# На вход на русском языке подаётся любое число от 0 до 999. Необходимо вывести
# это число в цифровом виде либо указать ошибки ввода во всплывающем окне,
# используя дерево разбора.
#
# Дерево разбора (БНФ):
#   Число   = "ноль" ! Сотни </ Хвост /> ! Хвост
#   Хвост   = Десятки </ Единицы /> ! Надцать ! Единицы
#   Сотни   = "сто" ! "двести" ! . . . ! "девятьсот"
#   Десятки = "двадцать" ! "тридцать" ! . . . ! "девяносто"
#   Надцать = "десять" ! "одиннадцать" ! . . . ! "девятнадцать"
#   Единицы = "один" ! "два" ! . . . ! "девять"
#
# Одно предложение БНФ = одна функция (число, хвост). Транслятор однопроходный:
# слово проверяется по словарю в тот момент, когда до него дошёл разбор,
# поэтому сообщение всегда относится к первой ошибке в тексте.

import sys

# ---------------------------------------------------------------
# 1. Словарь: слово -> (класс, значение)
# ---------------------------------------------------------------
СОТНИ = ["сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот",
         "семьсот", "восемьсот", "девятьсот"]
ДЕСЯТКИ = ["двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят",
           "семьдесят", "восемьдесят", "девяносто"]
НАДЦАТЬ = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
           "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"]
ЕДИНИЦЫ = ["один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]

СЛОВАРЬ = {"ноль": ("ноль", 0)}
for k, w in enumerate(СОТНИ, 1):
    СЛОВАРЬ[w] = ("сотни", 100 * k)
for k, w in enumerate(ДЕСЯТКИ, 2):
    СЛОВАРЬ[w] = ("десятки", 10 * k)
for k, w in enumerate(НАДЦАТЬ, 10):
    СЛОВАРЬ[w] = ("надцать", k)
for k, w in enumerate(ЕДИНИЦЫ, 1):
    СЛОВАРЬ[w] = ("единицы", k)

# Названия классов в сообщениях и их старшинство (для ошибки «стоять перед»).
ФОРМАТ = {"сотни": "формата сотен", "десятки": "десятичного формата",
          "надцать": "формата 10-19", "единицы": "единичного формата"}
СТАРШИНСТВО = {"сотни": 4, "десятки": 3, "надцать": 2, "единицы": 1}


class ОшибкаВвода(Exception):
    """Выход по ветке ИНАЧЕ: сообщение и выход."""


def место(i):
    """«во 2-м слове», «в 3-м слове»."""
    return f"{'во' if i == 2 else 'в'} {i}-м слове"


def текст_ошибки_порядка(i, пред, пред_слово, тек, тек_слово):
    """Слово номер i (класс тек) не может стоять после слова i-1 (класс пред)."""
    где = место(i).capitalize()
    if пред == "ноль" and тек == "ноль":
        return f"{где}: ноль не может сочетаться с другими числами"
    if пред == "ноль":
        return f"{где}: ноль не может сочетаться с числом {ФОРМАТ[тек]} ({тек_слово})"
    if тек == "ноль":
        return f"{где}: число {ФОРМАТ[пред]} ({пред_слово}) не может сочетаться с нулём"
    if пред == тек:
        return (f"{где}: число {ФОРМАТ[тек]} ({тек_слово}) не может стоять "
                f"за числом {ФОРМАТ[пред]} ({пред_слово})")
    if СТАРШИНСТВО[пред] < СТАРШИНСТВО[тек]:
        return (f"{где}: число {ФОРМАТ[пред]} ({пред_слово}) не может стоять "
                f"перед числом {ФОРМАТ[тек]} ({тек_слово})")
    return (f"{где}: число {ФОРМАТ[пред]} ({пред_слово}) не может сочетаться "
            f"с числом {ФОРМАТ[тек]} ({тек_слово})")


# ---------------------------------------------------------------
# 2. Транслятор: K — число слов, i — номер текущего слова (с единицы)
# ---------------------------------------------------------------
class Разбор:
    def __init__(self, текст):
        self.слова = текст.lower().replace("ё", "е").split()
        self.исходные = текст.split()          # для сообщений — как ввёл человек
        self.K = len(self.слова)
        self.i = 1
        self.сумма = 0

    # --- Слово i: лексический анализ одного слова ---
    def слово(self, i):
        w = self.слова[i - 1]
        if w not in СЛОВАРЬ:
            raise ОшибкаВвода(f"Ошибка {место(i)} ({self.исходные[i - 1]})")
        return СЛОВАРЬ[w]

    def принять(self, значение):
        self.сумма += значение
        self.i += 1

    def ошибка_порядка(self):
        пред, _ = self.слово(self.i - 1)
        тек, _ = self.слово(self.i)
        raise ОшибкаВвода(текст_ошибки_порядка(
            self.i, пред, self.исходные[self.i - 2], тек, self.исходные[self.i - 1]))

    # --- Число = "ноль" ! Сотни </ Хвост /> ! Хвост ---
    def число(self):
        класс, значение = self.слово(self.i)
        if класс == "ноль":
            self.принять(значение)
        elif класс == "сотни":
            self.принять(значение)
            if self.i <= self.K:                # </ Хвост />: есть ещё слова?
                self.хвост()
        else:
            self.хвост()
        if self.i <= self.K:                    # слова остались — лишнее слово
            self.ошибка_порядка()

    # --- Хвост = Десятки </ Единицы /> ! Надцать ! Единицы ---
    def хвост(self):
        класс, значение = self.слово(self.i)
        if класс == "десятки":
            self.принять(значение)
            if self.i <= self.K:                # </ Единицы />
                класс2, значение2 = self.слово(self.i)
                if класс2 == "единицы":
                    self.принять(значение2)
        elif класс in ("надцать", "единицы"):
            self.принять(значение)
        else:                                   # ИНАЧЕ
            self.ошибка_порядка()


def перевести(текст):
    """Возвращает (число, None) или (None, текст ошибки)."""
    р = Разбор(текст)
    if р.K == 0:
        return None, "Введите число от 0 до 999 словами"
    try:
        р.число()
    except ОшибкаВвода as e:
        return None, str(e)
    return р.сумма, None


