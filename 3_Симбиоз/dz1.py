def запустить_окно():
    import tkinter as tk
    from tkinter import ttk

    def по_центру(окно_, ширина=None, высота=None):
        окно_.update_idletasks()
        w = ширина or окно_.winfo_reqwidth()
        h = высота or окно_.winfo_reqheight()
        x = (окно_.winfo_screenwidth() - w) // 2
        y = (окно_.winfo_screenheight() - h) // 2
        if ширина and высота:
            окно_.geometry(f"{w}x{h}+{x}+{y}")
        else:
            окно_.geometry(f"+{x}+{y}")

    def показать_ошибку(текст):
        win = tk.Toplevel(окно)
        win.title("Ошибка ввода")
        win.transient(окно)
        win.grab_set()
        рамка = ttk.Frame(win, padding=12)
        рамка.grid(sticky="nsew")
        ttk.Label(рамка, text=текст, font=("Segoe UI", 11)).grid(row=0, column=0, sticky="w")
        ttk.Button(рамка, text="ОК", command=win.destroy).grid(row=1, column=0, pady=(10, 0), sticky="e")
        win.bind("<Return>", lambda событие: win.destroy())
        по_центру(win)

    def по_кнопке(событие=None):
        результат.set("")                       # старый ответ не остаётся рядом с ошибкой
        число, ошибка = перевести(поле_ввода.get())
        if ошибка:
            показать_ошибку(ошибка)
        else:
            результат.set(str(число))

    окно = tk.Tk()
    окно.title("Число прописью → цифрами")
    окно.columnconfigure(0, weight=1)
    окно.rowconfigure(0, weight=1)

    рамка = ttk.Frame(окно, padding=12)
    рамка.grid(sticky="nsew")
    рамка.columnconfigure(0, weight=1)

    поле_ввода = ttk.Entry(рамка, font=("Segoe UI", 12))
    поле_ввода.grid(row=0, column=0, sticky="ew", padx=(0, 8))
    поле_ввода.bind("<Return>", по_кнопке)
    поле_ввода.focus_set()

    ttk.Button(рамка, text="Перевести", command=по_кнопке).grid(row=0, column=1)

    результат = tk.StringVar()
    ttk.Entry(рамка, textvariable=результат, font=("Segoe UI", 12), state="readonly").grid(
        row=1, column=0, columnspan=2, sticky="ew", pady=(12, 0))

    ttk.Label(рамка, text='Введите число от 0 до 999 словами (пример: "девятьсот один").').grid(
        row=2, column=0, columnspan=2, sticky="w", pady=(8, 0))

    по_центру(окно, 560, 160)
    окно.mainloop()


