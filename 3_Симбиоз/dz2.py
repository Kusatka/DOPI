def запустить_окно():
    import tkinter as tk

    def по_центру(окно_, ширина, высота):
        x = (окно_.winfo_screenwidth() - ширина) // 2
        y = (окно_.winfo_screenheight() - высота) // 2
        окно_.geometry(f"{ширина}x{высота}+{x}+{y}")

    def показать_ошибку(текст):
        win = tk.Toplevel(окно)
        win.title("Ошибка")
        по_центру(win, 420, 150)
        win.resizable(False, False)
        win.transient(окно)
        win.grab_set()
        рамка = tk.Frame(win)
        рамка.pack(expand=True, fill="both", padx=20, pady=20)
        tk.Label(рамка, text=текст, font=("Arial", 10), wraplength=380,
                 justify="center").pack(pady=(0, 15))
        tk.Button(рамка, text="ОК", font=("Arial", 10), width=10, command=win.destroy,
                  bg="#f44336", fg="white", cursor="hand2").pack()
        win.bind("<Return>", lambda событие: win.destroy())

    def показать_результат(текст):
        поле_результата.config(state="normal")
        поле_результата.delete("1.0", tk.END)
        поле_результата.insert("1.0", текст)
        поле_результата.config(state="disabled")

    def по_кнопке():
        показать_результат("")                  # старый результат не остаётся рядом с ошибкой
        результат, ошибка = выполнить(поле1.get(), поле2.get())
        if ошибка:
            показать_ошибку(ошибка)
        else:
            показать_результат(результат)

    окно = tk.Tk()
    окно.title("Шахматный порядок чисел")
    по_центру(окно, 500, 300)
    окно.grid_rowconfigure(4, weight=1)
    окно.grid_columnconfigure(1, weight=1)

    tk.Label(окно, text="Первая строка:", font=("Arial", 11)).grid(
        row=0, column=0, padx=10, pady=10, sticky="e")
    поле1 = tk.Entry(окно, font=("Arial", 11))
    поле1.grid(row=0, column=1, padx=10, pady=10, sticky="ew")

    tk.Label(окно, text="Вторая строка:", font=("Arial", 11)).grid(
        row=1, column=0, padx=10, pady=10, sticky="e")
    поле2 = tk.Entry(окно, font=("Arial", 11))
    поле2.grid(row=1, column=1, padx=10, pady=10, sticky="ew")

    tk.Button(окно, text="Вывести в шахматном порядке", font=("Arial", 11, "bold"),
              bg="#8890E5", fg="white", activebackground="#b1abe7", cursor="hand2",
              command=по_кнопке).grid(row=2, column=0, columnspan=2, pady=15, padx=50, sticky="ew")

    tk.Label(окно, text="Результат:", font=("Arial", 11, "bold")).grid(
        row=3, column=0, columnspan=2, padx=10, pady=(10, 5), sticky="w")
    поле_результата = tk.Text(окно, font=("Arial", 10), height=5, state="disabled", wrap="word")
    поле_результата.grid(row=4, column=0, columnspan=2, padx=10, pady=(0, 10), sticky="nsew")

    for поле in (поле1, поле2):
        поле.bind("<Return>", lambda событие: по_кнопке())
    поле1.focus_set()
    окно.mainloop()


