ТЕСТЫ_ВЕРНЫЕ = [
    ("43 236 764 542 2 23 5 8", "345  543653     4 2  7 7867 7",
     "43 345 236 543653 764 4 542 2 2 7 23 7867 5 7 8"),
    ("43 236 764", "345 543653", "43 345 236 543653 764"),        # первая длиннее
    ("1", "2 3 4", "1 2 3 4"),                                     # вторая длиннее
    ("1 2 3", "4 5 6", "1 4 2 5 3 6"),                             # равной длины
    ("-5 3.5", "0,25 +7", "-5 0,25 3.5 +7"),                       # знаки и дроби
    ("007 3.50", "12345678901234567890", "007 12345678901234567890 3.50"),  # как ввели
    ("  7  ", "8", "7 8"),                                         # пробелы по краям
]
ТЕСТЫ_ОШИБОЧНЫЕ = [
    ("44 2 2 канье", "5 3 4 5", "Ошибка: 'канье' не является корректным числом! (1-я строка, 4-е слово)"),
    ("1 2", "3 x 4", "Ошибка: 'x' не является корректным числом! (2-я строка, 2-е слово)"),
    ("", "1 2", "Ошибка: поле «Первая строка» не заполнено!"),
    ("1 2", "   ", "Ошибка: поле «Вторая строка» не заполнено!"),
    ("1 abc", "", "Ошибка: 'abc' не является корректным числом! (1-я строка, 2-е слово)"),
    ("1.2.3", "4", "Ошибка: '1.2.3' не является корректным числом! (1-я строка, 1-е слово)"),
    ("1-2", "4", "Ошибка: '1-2' не является корректным числом! (1-я строка, 1-е слово)"),
    ("nan", "4", "Ошибка: 'nan' не является корректным числом! (1-я строка, 1-е слово)"),
    ("1e5", "4", "Ошибка: '1e5' не является корректным числом! (1-я строка, 1-е слово)"),
    ("１２", "4", "Ошибка: '１２' не является корректным числом! (1-я строка, 1-е слово)"),
    ("5.", "4", "Ошибка: '5.' не является корректным числом! (1-я строка, 1-е слово)"),
]


def самопроверка():
    провалы = 0
    for a, b, ждём in ТЕСТЫ_ВЕРНЫЕ:
        r, e = выполнить(a, b)
        if r != ждём:
            провалы += 1
            print(f"ПРОВАЛ: «{a}» / «{b}» -> {r!r}, {e!r}; ждали {ждём!r}")
    for a, b, ждём in ТЕСТЫ_ОШИБОЧНЫЕ:
        r, e = выполнить(a, b)
        if e != ждём:
            провалы += 1
            print(f"ПРОВАЛ: «{a}» / «{b}» -> {e!r}; ждали {ждём!r}")
    print("Все тесты прошли" if провалы == 0 else f"Провалов: {провалы}")
    return провалы


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "test":
        sys.exit(1 if самопроверка() else 0)
    else:
        запустить_окно()
